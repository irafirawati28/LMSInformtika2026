CREATE TABLE IF NOT EXISTS learning_game_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  learning_game_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  score SMALLINT NOT NULL,
  max_score SMALLINT NOT NULL,
  passed BOOLEAN NOT NULL,
  answers JSONB NOT NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_learning_game_attempts_game
    FOREIGN KEY (learning_game_id) REFERENCES learning_games (id),
  CONSTRAINT fk_learning_game_attempts_student
    FOREIGN KEY (student_id) REFERENCES students (user_id),
  CONSTRAINT chk_learning_game_attempts_score
    CHECK (score >= 0 AND max_score > 0 AND score <= max_score)
);

CREATE INDEX IF NOT EXISTS idx_learning_game_attempts_student_game
  ON learning_game_attempts (student_id, learning_game_id, submitted_at DESC);

ALTER TABLE learning_game_attempts ENABLE ROW LEVEL SECURITY;
