CREATE TABLE IF NOT EXISTS assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  class_id BIGINT NOT NULL,
  module_id BIGINT NULL,
  title VARCHAR(180) NOT NULL,
  description TEXT NULL,
  instructions TEXT NULL,
  starts_at TIMESTAMPTZ NULL,
  due_at TIMESTAMPTZ NULL,
  weight DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  is_required BOOLEAN NOT NULL DEFAULT TRUE,
  allow_late_submission BOOLEAN NOT NULL DEFAULT FALSE,
  allow_revision BOOLEAN NOT NULL DEFAULT FALSE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_assignments_module_id UNIQUE (module_id, id),
  CONSTRAINT fk_assignments_class FOREIGN KEY (class_id) REFERENCES classes (id),
  CONSTRAINT fk_assignments_module_class FOREIGN KEY (class_id, module_id) REFERENCES modules (class_id, id),
  CONSTRAINT chk_assignments_weight CHECK (weight >= 0 AND weight <= 100),
  CONSTRAINT chk_assignments_dates CHECK (starts_at IS NULL OR due_at IS NULL OR starts_at <= due_at)
);

CREATE TABLE IF NOT EXISTS assessments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  class_id BIGINT NOT NULL,
  module_id BIGINT NULL,
  title VARCHAR(180) NOT NULL,
  description TEXT NULL,
  starts_at TIMESTAMPTZ NULL,
  due_at TIMESTAMPTZ NULL,
  time_limit_minutes SMALLINT NULL,
  max_attempts SMALLINT NOT NULL DEFAULT 1,
  pass_score DECIMAL(5,2) NULL,
  is_required BOOLEAN NOT NULL DEFAULT TRUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_assessments_module_id UNIQUE (module_id, id),
  CONSTRAINT fk_assessments_class FOREIGN KEY (class_id) REFERENCES classes (id),
  CONSTRAINT fk_assessments_module_class FOREIGN KEY (class_id, module_id) REFERENCES modules (class_id, id),
  CONSTRAINT chk_assessments_pass_score CHECK (pass_score IS NULL OR (pass_score >= 0 AND pass_score <= 100)),
  CONSTRAINT chk_assessments_dates CHECK (starts_at IS NULL OR due_at IS NULL OR starts_at <= due_at),
  CONSTRAINT chk_assessments_max_attempts CHECK (max_attempts BETWEEN 1 AND 255)
);

CREATE TABLE IF NOT EXISTS questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  assessment_id BIGINT NOT NULL,
  question_type TEXT NOT NULL CHECK (question_type IN ('MULTIPLE_CHOICE', 'TRUE_FALSE', 'SHORT_ANSWER', 'ESSAY')),
  prompt TEXT NOT NULL,
  options JSONB NULL,
  answer_key JSONB NULL,
  points DECIMAL(7,2) NOT NULL DEFAULT 0.00,
  position INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_questions_position UNIQUE (assessment_id, position),
  CONSTRAINT fk_questions_assessment FOREIGN KEY (assessment_id) REFERENCES assessments (id),
  CONSTRAINT chk_questions_points CHECK (points >= 0),
  CONSTRAINT chk_questions_position CHECK (position >= 0)
);

CREATE TABLE IF NOT EXISTS assignment_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  assignment_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  attempt_number SMALLINT NOT NULL,
  submission_type TEXT NOT NULL CHECK (submission_type IN ('FILE', 'LINK', 'TEXT')),
  file_key VARCHAR(512) NULL,
  external_url VARCHAR(2048) NULL,
  response_text TEXT NULL,
  status TEXT NOT NULL CHECK (status IN ('SUBMITTED', 'LATE', 'GRADED')),
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_assignment_submission_attempt UNIQUE (assignment_id, student_id, attempt_number),
  CONSTRAINT uq_assignment_submissions_id_student UNIQUE (id, student_id),
  CONSTRAINT fk_assignment_submissions_assignment FOREIGN KEY (assignment_id) REFERENCES assignments (id),
  CONSTRAINT fk_assignment_submissions_student FOREIGN KEY (student_id) REFERENCES students (user_id),
  CONSTRAINT chk_assignment_submission_attempt CHECK (attempt_number > 0),
  CONSTRAINT chk_assignment_submission_payload CHECK (
    (submission_type = 'FILE' AND file_key IS NOT NULL)
    OR (submission_type = 'LINK' AND external_url IS NOT NULL)
    OR (submission_type = 'TEXT' AND response_text IS NOT NULL)
  )
);

CREATE TABLE IF NOT EXISTS assessment_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  assessment_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  attempt_number SMALLINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'GRADED')),
  started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  submitted_at TIMESTAMPTZ NULL,
  PRIMARY KEY (id),
  CONSTRAINT uq_assessment_attempt_number UNIQUE (assessment_id, student_id, attempt_number),
  CONSTRAINT uq_assessment_attempts_id_student UNIQUE (id, student_id),
  CONSTRAINT fk_assessment_attempts_assessment FOREIGN KEY (assessment_id) REFERENCES assessments (id),
  CONSTRAINT fk_assessment_attempts_student FOREIGN KEY (student_id) REFERENCES students (user_id),
  CONSTRAINT chk_assessment_attempt_number CHECK (attempt_number BETWEEN 1 AND 255)
);

CREATE TABLE IF NOT EXISTS assessment_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  attempt_id BIGINT NOT NULL,
  question_id BIGINT NOT NULL,
  answer JSONB NULL,
  awarded_points DECIMAL(7,2) NULL,
  feedback TEXT NULL,
  answered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_assessment_answer_question UNIQUE (attempt_id, question_id),
  CONSTRAINT fk_assessment_answers_attempt FOREIGN KEY (attempt_id) REFERENCES assessment_attempts (id),
  CONSTRAINT fk_assessment_answers_question FOREIGN KEY (question_id) REFERENCES questions (id),
  CONSTRAINT chk_assessment_answer_points CHECK (awarded_points IS NULL OR awarded_points >= 0)
);

CREATE TABLE IF NOT EXISTS grades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  student_id BIGINT NOT NULL,
  assignment_submission_id BIGINT NULL,
  assessment_attempt_id BIGINT NULL,
  graded_by BIGINT NOT NULL,
  score DECIMAL(7,2) NOT NULL,
  max_score DECIMAL(7,2) NOT NULL,
  feedback TEXT NULL,
  graded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_grades_assignment_submission UNIQUE (assignment_submission_id),
  CONSTRAINT uq_grades_assessment_attempt UNIQUE (assessment_attempt_id),
  CONSTRAINT fk_grades_student FOREIGN KEY (student_id) REFERENCES students (user_id),
  CONSTRAINT fk_grades_submission_student FOREIGN KEY (assignment_submission_id, student_id) REFERENCES assignment_submissions (id, student_id),
  CONSTRAINT fk_grades_assessment_student FOREIGN KEY (assessment_attempt_id, student_id) REFERENCES assessment_attempts (id, student_id),
  CONSTRAINT fk_grades_teacher FOREIGN KEY (graded_by) REFERENCES teachers (user_id),
  CONSTRAINT chk_grades_one_source CHECK (
    (assignment_submission_id IS NOT NULL AND assessment_attempt_id IS NULL)
    OR (assignment_submission_id IS NULL AND assessment_attempt_id IS NOT NULL)
  ),
  CONSTRAINT chk_grades_score CHECK (score >= 0 AND max_score > 0 AND score <= max_score)
);

CREATE TABLE IF NOT EXISTS student_content_progress (
  student_id BIGINT NOT NULL,
  module_content_id BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'NOT_STARTED' CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED', 'PENDING_REVIEW')),
  started_at TIMESTAMPTZ NULL,
  completed_at TIMESTAMPTZ NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (student_id, module_content_id),
  CONSTRAINT fk_content_progress_student FOREIGN KEY (student_id) REFERENCES students (user_id),
  CONSTRAINT fk_content_progress_content FOREIGN KEY (module_content_id) REFERENCES module_contents (id)
);

CREATE TABLE IF NOT EXISTS student_module_progress (
  student_id BIGINT NOT NULL,
  module_id BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'LOCKED' CHECK (status IN ('LOCKED', 'IN_PROGRESS', 'PENDING_REVIEW', 'COMPLETED')),
  progress_percent SMALLINT NOT NULL DEFAULT 0,
  started_at TIMESTAMPTZ NULL,
  completed_at TIMESTAMPTZ NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (student_id, module_id),
  CONSTRAINT fk_module_progress_student FOREIGN KEY (student_id) REFERENCES students (user_id),
  CONSTRAINT fk_module_progress_module FOREIGN KEY (module_id) REFERENCES modules (id),
  CONSTRAINT chk_module_progress_percent CHECK (progress_percent BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS module_requirements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  module_id BIGINT NOT NULL,
  module_content_id BIGINT NULL,
  assignment_id BIGINT NULL,
  assessment_id BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_module_requirement_content UNIQUE (module_id, module_content_id),
  CONSTRAINT uq_module_requirement_assignment UNIQUE (module_id, assignment_id),
  CONSTRAINT uq_module_requirement_assessment UNIQUE (module_id, assessment_id),
  CONSTRAINT fk_module_requirements_content FOREIGN KEY (module_id, module_content_id) REFERENCES module_contents (module_id, id),
  CONSTRAINT fk_module_requirements_assignment FOREIGN KEY (module_id, assignment_id) REFERENCES assignments (module_id, id),
  CONSTRAINT fk_module_requirements_assessment FOREIGN KEY (module_id, assessment_id) REFERENCES assessments (module_id, id),
  CONSTRAINT chk_module_requirement_target CHECK (
    (module_content_id IS NOT NULL AND assignment_id IS NULL AND assessment_id IS NULL)
    OR (module_content_id IS NULL AND assignment_id IS NOT NULL AND assessment_id IS NULL)
    OR (module_content_id IS NULL AND assignment_id IS NULL AND assessment_id IS NOT NULL)
  )
);

CREATE TABLE IF NOT EXISTS attendance_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  class_id BIGINT NOT NULL,
  created_by BIGINT NOT NULL,
  session_date DATE NOT NULL,
  title VARCHAR(180) NULL,
  notes TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
